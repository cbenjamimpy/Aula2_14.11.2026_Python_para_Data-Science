# Exemplo 2 - Tipos de prints com os tipos de dados em Python

# Variavel para armazenar o nome do aluno
nome_aluno = 'Celso' # declara a variavel
idade_aluno = 37 # variavel com a idade do aluno
media_aluno = 10.0 # declaração de variavel

print('Nome do aluno é %s, ele tem %d anos e sua média é %.2f.' %(nome_aluno,idade_aluno,media_aluno))
print('Nome do aluno é %s, ele tem %d anos e sua média é %.2f.' %(nome_aluno,idade_aluno,media_aluno))
print('Nome do aluno é {}, ele tem {} anos e sua média é {:.2f}.'.format(nome_aluno,idade_aluno,media_aluno))
print(f'Nome do aluno é {nome_aluno}, ele tem {idade_aluno} anos e sua média é {media_aluno:.2f}.')