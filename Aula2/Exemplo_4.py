# Exemplo 4 - Entrada de números inteiros - int ()

nome = input ("Digite o nome do aluno: ") # Armazena o nome do aluno na variavel 'nome'
idade = int(input("Digite a idade: ")) # Armazena a idade do aluno na variavel 'idade'

print(f"O aluno {nome} tem {idade} anos.") # Exibe o nome e a idade do aluno usando f-string para formatação da saída
